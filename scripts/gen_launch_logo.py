#!/usr/bin/env python3
"""Regenerate `bot_bottle/cli/logo.py` from the brand's glass bottle.

Rasterizes the SVG at the panel size with `rsvg-convert`, reads the pixels
with ImageMagick, and writes them as rows of palette characters. That keeps
the CLI stdlib-only: the art is data, and rendering it is a lookup. Only a
maintainer changing the artwork needs these tools.

Usage: scripts/gen_launch_logo.py <bot-bottle-brand>/bottle-glass.svg [width]
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "bot_bottle" / "cli" / "logo.py"
ALPHA_MIN = 110  # below this a pixel is background (drops the soft shadow)
CHARS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"


def pixels(svg: str, width: int) -> list[list[str | None]]:
    png = subprocess.run(["rsvg-convert", "-w", str(width), svg], check=True,
                         capture_output=True).stdout
    size = subprocess.run(["magick", "identify", "-format", "%w %h", "png:-"], input=png,
                          check=True, capture_output=True).stdout.split()
    w, h = int(size[0]), int(size[1])
    raw = subprocess.run(["magick", "png:-", "-depth", "8", "rgba:-"], input=png,
                         check=True, capture_output=True).stdout
    rows: list[list[str | None]] = []
    for y in range(h):
        row: list[str | None] = []
        for x in range(w):
            r, g, b, a = raw[(y * w + x) * 4:(y * w + x) * 4 + 4]
            # Quantize lightly so the palette stays small.
            row.append(None if a < ALPHA_MIN else
                       f"{r // 16 * 16:02x}{g // 16 * 16:02x}{b // 16 * 16:02x}")
        rows.append(row)
    while rows and all(p is None for p in rows[-1]):
        rows.pop()
    return rows


# At 28 px the anti-aliased ">_" blurs into a smudge, so it's redrawn as
# crisp pixel art: (row, first column, last column) runs in the prompt copper,
# over the glass's dark interior.
PROMPT_COPPER = "e08850"
GLASS = "101010"
PROMPT_AREA = (15, 22, 7, 21)  # rows [15, 22), columns [7, 21) are cleared
PROMPT = (
    (15, 9, 10), (16, 10, 11), (17, 11, 12), (18, 12, 13),  # > (top half and tip)
    (19, 11, 12), (20, 10, 11), (21, 9, 10),  # > (bottom half)
    (21, 15, 19),  # _
)
CURSOR = PROMPT[-1]  # the "_", which blinks


def redraw_prompt(rows: list[list[str | None]]) -> None:
    top, bottom, left, right = PROMPT_AREA
    for y in range(top, bottom):
        for x in range(left, right):
            rows[y][x] = GLASS
    for y, first, last in PROMPT:
        for x in range(first, last + 1):
            rows[y][x] = PROMPT_COPPER


def main(svg: str, width: int = 28) -> None:
    rows = pixels(svg, width)
    if width == 28:
        redraw_prompt(rows)
    colors = sorted({p for row in rows for p in row if p})
    if len(colors) > len(CHARS):
        sys.exit(f"{len(colors)} colors; quantize harder")
    key = dict(zip(colors, CHARS))
    art = ["".join(key[p] if p else "." for p in row) for row in rows]
    palette = "\n".join(f'    "{c}": "{h}",' for h, c in key.items())
    body = "\n".join(f'    "{line}",' for line in art)
    cursor = (f"\n# The prompt's blinking cursor: (row, first column, last column), and\n"
              f"# the pixel it shows when off.\nCURSOR: tuple[int, int, int] = {CURSOR}\n"
              f'CURSOR_OFF = "{key[GLASS]}"\n') if width == 28 else ""
    OUT.write_text(f'''"""The bot-bottle glass bottle as terminal art, for the launch panel.

Generated by scripts/gen_launch_logo.py from the brand's bottle-glass.svg;
don't edit by hand. Each character is one pixel ("." is background); two
pixel rows make one terminal row, drawn with half blocks.
"""

from __future__ import annotations

PALETTE: dict[str, str] = {{
{palette}
}}

ART: tuple[str, ...] = (
{body}
)
{cursor}''')
    print(f"wrote {OUT} ({len(art[0])}x{len(art)} px, {len(colors)} colors)")


if __name__ == "__main__":
    main(sys.argv[1], *(int(a) for a in sys.argv[2:3]))
